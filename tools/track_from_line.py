#!/usr/bin/env python3
"""Builds config/tracks.lua for one raceway from one recorded lap.

Usage:  python3 tools/track_from_line.py <line.json> [--name Grand_Senora] [--out config/tracks.lua]

<line.json> is the `points` value of a row in dps_proracing_lines: a list of {x, y, z, h}
recorded with /recordline. From that one lap this writes the checkpoints, the finish line,
the starting grid, the place a finished racer is put, and the lobby host's spot. Record the
lap starting on the start/finish line, driving the racing direction.
"""
import argparse, json, math, sys

ap = argparse.ArgumentParser()
ap.add_argument('line')
ap.add_argument('--name', default='Grand_Senora')
ap.add_argument('--out', default='config/tracks.lua')
ap.add_argument('--checkpoint-every', type=float, default=180.0, help='metres between checkpoints')
ap.add_argument('--grid', type=int, default=8, help='starting places')
ap.add_argument('--paddock', type=float, nargs=4, metavar=('X', 'Y', 'Z', 'H'),
                help='where the lobby host stands (default: 14 m to the right of the start line)')
a = ap.parse_args()

pts = json.load(open(a.line))
P = [(p['x'], p['y'], p['z']) for p in pts]
n = len(P)
if n < 10:
    sys.exit('line too short')

def d(i, j): return math.dist(P[i % n][:2], P[j % n][:2])
cum = [0.0]
for i in range(n): cum.append(cum[-1] + d(i, i + 1))
lap = cum[-1]

def at(s):
    """Point and direction of travel at distance s along the lap."""
    s %= lap
    i = max(k for k in range(n) if cum[k] <= s)
    j = (i + 1) % n
    seg = cum[i + 1] - cum[i] or 1.0
    t = (s - cum[i]) / seg
    x = P[i][0] + (P[j][0] - P[i][0]) * t; y = P[i][1] + (P[j][1] - P[i][1]) * t; z = P[i][2] + (P[j][2] - P[i][2]) * t
    dx, dy = P[j][0] - P[i][0], P[j][1] - P[i][1]
    L = math.hypot(dx, dy) or 1.0
    return (x, y, z), (dx / L, dy / L)

def heading(dx, dy):  # GTA heading: 0 = north (+y), counter-clockwise
    return math.degrees(math.atan2(-dx, dy)) % 360.0

count = max(3, round(lap / a.checkpoint_every))
cps = [at(lap * k / (count + 1))[0] for k in range(1, count + 1)]

start, (fx, fy) = at(0.0)
rx, ry = fy, -fx   # to the right of the direction of travel

grid = []
for k in range(a.grid):
    row, side = k // 2, (-1 if k % 2 == 0 else 1)
    (x, y, z), (dx, dy) = at(-(8.0 + row * 9.0) - (0.0 if side < 0 else 4.5))
    grid.append((x + (dy) * 2.6 * side, y + (-dx) * 2.6 * side, z, heading(dx, dy)))

pad = a.paddock or (start[0] + rx * 14.0, start[1] + ry * 14.0, start[2], (heading(fx, fy) + 90.0) % 360.0)
out = (pad[0] + fx * 4.0, pad[1] + fy * 4.0, pad[2], pad[3])

v3 = lambda p: 'vector3(%.2f, %.2f, %.2f)' % p
v4 = lambda p: 'vector4(%.4f, %.4f, %.4f, %.4f)' % p
L = []
w = L.append
w('Config = Config or {}')
w('')
w('-- GENERATED by tools/track_from_line.py from one recorded lap. Do not edit by hand:')
w('-- record the lap again with /recordline and run the tool again.')
w('--   lap length %.0f m, %d checkpoints, %d grid places' % (lap, count, a.grid))
w('')
w('--- START / FINISH LINE')
w('Config.StartLinePoints = {')
w('  %s,' % v3(start))
w('}')
w('')
w('--- TRACK CHECKPOINTS (driven through in order). One layout: the full lap.')
w('Config.Checkpoints = {')
w('    %s = {' % a.name)
for i, c in enumerate(cps, 1): w('        %s,  -- CP%d' % (v3(c), i))
w('    },')
w('}')
w('')
w('--- OUT COORDS (where a racer is put after the finish)')
w('Config.outCoords = %s' % v4(out))
w('')
w('--- LOBBY HOST' + ('' if a.paddock else '  (PROVISIONAL: placed beside the start line. Pass --paddock x y z h for the real spot.)'))
w('Config.LobbyPed = {')
w("    model  = 's_m_y_valet_01',")
w('    coords = %s,' % v4(pad))
w('}')
w('')
w('--- TRACK PROPS / BARRIERS (none: the raceway map has its own)')
w('Config.TrackProps = {')
w('    ["%s"] = {},' % a.name)
w('}')
w('')
w('--- GRID SPAWN POINTS (two columns behind the start line, pole first)')
w('Config.GridSpawnPoints = {')
for g in grid: w('    %s,' % v4(g))
w('}')
w('')
w('--- FINISH LINE SPHERE')
w('Config.FinishLine = {')
w('    coords = Config.StartLinePoints[1],')
w('    radius = 15.0,')
w('}')
open(a.out, 'w').write('\n'.join(L) + '\n')
print('wrote %s: lap %.0f m, %d checkpoints, %d grid places' % (a.out, lap, count, a.grid))
